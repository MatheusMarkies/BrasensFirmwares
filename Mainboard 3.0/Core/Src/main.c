/* USER CODE BEGIN 4 */
void KX122_Init(I2C_HandleTypeDef *hi2c) {
    uint8_t data[2];

    // Verificar o ID do dispositivo
    HAL_I2C_Mem_Read(hi2c, KX122_ADDR, KX122_WHO_AM_I, 1, &data[0], 1, HAL_MAX_DELAY);

    if (data[0] != 0x1A) {  // Valor esperado do WHO_AM_I
        // Dispositivo não encontrado ou ID incorreto
        printf("Erro: ID do dispositivo incorreto (0x%X)\n", data[0]);
        while (1);
    } else {
        printf("ID do dispositivo correto (0x%X)\n", data[0]);
    }

    // Configurar o KX122-1037 (ativar e configurar o sensor)
    data[0] = KX122_CTRL_REG1;
    data[1] = 0x80;  // Configurar modo de operação (ativar sensor)
    HAL_I2C_Mem_Write(hi2c, KX122_ADDR, data[0], 1, &data[1], 1, HAL_MAX_DELAY);
    printf("CTRL_REG1 configurado (0x%X)\n", data[1]);

    data[0] = KX122_DATA_CTRL_REG;
    data[1] = 0x0F;  // Configurar taxa de saída de dados para 25,600 Hz
    HAL_I2C_Mem_Write(hi2c, KX122_ADDR, data[0], 1, &data[1], 1, HAL_MAX_DELAY);
    printf("DATA_CTRL_REG configurado (0x%X)\n", data[1]);
}

void KX122_ReadAccel(I2C_HandleTypeDef *hi2c, int16_t *x, int16_t *y, int16_t *z) {
    uint8_t buffer[6];

    // Ler os dados do acelerômetro (6 bytes: X_L, X_H, Y_L, Y_H, Z_L, Z_H)
    HAL_I2C_Mem_Read(hi2c, KX122_ADDR, KX122_XOUT_L, 1, buffer, 6, HAL_MAX_DELAY);

    // Converter os dados lidos para valores de 16 bits
    *x = (int16_t)(buffer[1] << 8 | buffer[0]);
    *y = (int16_t)(buffer[3] << 8 | buffer[2]);
    *z = (int16_t)(buffer[5] << 8 | buffer[4]);
}

